"""Authenticated repair agent for incorrectly flattened TV seasons.

Cloud media is renamed/moved in place through CloudDrive2 first, then the local
Symedia STRM/NFO/art tree is rebuilt from that canonical layout.  Every apply
operation creates a local metadata backup and a reversible cloud move manifest.
"""
from __future__ import annotations

import json
import os
import re
import secrets
import shutil
import sqlite3
import tarfile
import threading
import time
from pathlib import Path

from fastapi import APIRouter, HTTPException, Request
import httpx

router = APIRouter(prefix="/season-repair", tags=["season-repair"])

ROOT = Path(os.getenv("SEASON_REPAIR_ROOT", "/home/symedia_gd/tvshows"))
CLOUD_ROOT = Path(os.getenv("SEASON_REPAIR_CLOUD_ROOT", "/cloud-tvshows"))
CLOUD_STRM_PREFIX = Path(os.getenv(
    "SEASON_REPAIR_CLOUD_STRM_PREFIX",
    "/CloudNAS/CloudDrive/GoogleDrive/zero/media/symedia_gd/tvshows",
))
TOKEN_FILE = Path(os.getenv("SEASON_REPAIR_TOKEN_FILE", "/data/season_repair_token"))
STATE_DIR = Path(os.getenv("SEASON_REPAIR_STATE_DIR", "/data/season-repair"))
DB_PATH = Path(os.getenv("DB_PATH", "/data/app.db"))
EP_RE = re.compile(r"(?i)S(?P<season>\d{1,3})E(?P<episode>\d{1,4})")
TMDB_RE = re.compile(r"(?i)\{tmdb-(\d+)\}")
ALLOWED_SUFFIXES = {".strm", ".nfo", ".jpg", ".jpeg", ".png", ".webp", ".srt", ".ass", ".ssa"}
VIDEO_SUFFIXES = {".mp4", ".mkv", ".ts", ".iso", ".rmvb", ".avi", ".mov", ".mpeg", ".mpg", ".wmv", ".m4v", ".flv", ".m2ts"}
CLOUD_MOVE_SUFFIXES = VIDEO_SUFFIXES | (ALLOWED_SUFFIXES - {".strm"})
SUPPRESSION_FILE = STATE_DIR / "notification_suppressions.json"
SUPPRESSION_LOCK = threading.Lock()


def _token() -> str:
    TOKEN_FILE.parent.mkdir(parents=True, exist_ok=True)
    if TOKEN_FILE.exists():
        value = TOKEN_FILE.read_text(encoding="utf-8").strip()
        if value:
            return value
    value = secrets.token_urlsafe(48)
    TOKEN_FILE.write_text(value, encoding="utf-8")
    os.chmod(TOKEN_FILE, 0o600)
    return value


def _normalize_series_label(value: str) -> str:
    value = re.sub(r"(?i)\s*\{tmdb-\d+\}\s*", " ", str(value or ""))
    value = re.sub(r"\s*\(\d{4}\)\s*$", "", value)
    return re.sub(r"\s+", " ", value).strip().casefold()


def _load_suppressions() -> list[dict]:
    try:
        data = json.loads(SUPPRESSION_FILE.read_text(encoding="utf-8"))
        return data if isinstance(data, list) else []
    except Exception:
        return []


def _save_suppressions(rows: list[dict]) -> None:
    SUPPRESSION_FILE.parent.mkdir(parents=True, exist_ok=True)
    temporary = SUPPRESSION_FILE.with_suffix(".tmp")
    temporary.write_text(json.dumps(rows, ensure_ascii=False, indent=2), encoding="utf-8")
    temporary.replace(SUPPRESSION_FILE)


def _register_notification_suppression(series: Path, seconds: int = 3600) -> None:
    relative = series.relative_to(ROOT.resolve()).as_posix()
    row = {
        "series_rel": relative,
        "series_name": _normalize_series_label(series.name),
        "expires_at": time.time() + max(300, int(seconds)),
    }
    with SUPPRESSION_LOCK:
        rows = [
            item for item in _load_suppressions()
            if float(item.get("expires_at") or 0) > time.time()
            and item.get("series_rel") != relative
        ]
        rows.append(row)
        _save_suppressions(rows)


def _remove_notification_suppression(series: Path) -> None:
    relative = series.relative_to(ROOT.resolve()).as_posix()
    with SUPPRESSION_LOCK:
        rows = [item for item in _load_suppressions() if item.get("series_rel") != relative]
        _save_suppressions(rows)


def notification_suppressed(item: dict) -> bool:
    """True for Emby webhook items generated by a season-repair rescan."""
    now = time.time()
    candidate_name = _normalize_series_label(
        item.get("SeriesName") or item.get("Series") or item.get("Name") or ""
    )
    candidate_path = str(item.get("Path") or "").replace("\\", "/").casefold()
    with SUPPRESSION_LOCK:
        all_rows = _load_suppressions()
        rows = [entry for entry in all_rows if float(entry.get("expires_at") or 0) > now]
        if len(rows) != len(all_rows):
            _save_suppressions(rows)
    for entry in rows:
        series_name = str(entry.get("series_name") or "")
        relative = str(entry.get("series_rel") or "").casefold()
        if series_name and candidate_name == series_name:
            return True
        if relative and relative in candidate_path:
            return True
    return False


def _authorize(request: Request) -> None:
    supplied = request.headers.get("authorization", "")
    expected = f"Bearer {_token()}"
    if not secrets.compare_digest(supplied, expected):
        raise HTTPException(status_code=401, detail="invalid repair token")


def _inside(path: Path, root_path: Path) -> Path:
    resolved = path.resolve()
    root = root_path.resolve()
    if resolved != root and root not in resolved.parents:
        raise HTTPException(status_code=400, detail="path outside repair root")
    return resolved


def _inside_root(path: Path) -> Path:
    return _inside(path, ROOT)


def _inside_cloud(path: Path) -> Path:
    return _inside(path, CLOUD_ROOT)


def _series_path(relative: str) -> Path:
    relative = str(relative or "").strip().replace("\\", "/").lstrip("/")
    if not relative or ".." in Path(relative).parts:
        raise HTTPException(status_code=400, detail="invalid series path")
    path = _inside_root(ROOT / relative)
    if not path.is_dir():
        raise HTTPException(status_code=404, detail="series directory not found")
    return path


def _cloud_series_path(relative: str) -> Path:
    relative = str(relative or "").strip().replace("\\", "/").lstrip("/")
    if not relative or ".." in Path(relative).parts:
        raise HTTPException(status_code=400, detail="invalid cloud series path")
    path = _inside_cloud(CLOUD_ROOT / relative)
    if not path.is_dir():
        raise HTTPException(status_code=404, detail="cloud series directory not found")
    return path


def _scan_series(path: Path) -> dict:
    episodes: dict[int, set[int]] = {}
    strm_count = 0
    for file in path.rglob("*.strm"):
        match = EP_RE.search(file.name)
        if not match:
            continue
        season = int(match.group("season"))
        episode = int(match.group("episode"))
        episodes.setdefault(season, set()).add(episode)
        strm_count += 1
    seasons = []
    for season, values in sorted(episodes.items()):
        ordered = sorted(values)
        missing = [n for n in range(ordered[0], ordered[-1] + 1) if n not in values] if ordered else []
        seasons.append({
            "season": season,
            "count": len(ordered),
            "min": ordered[0] if ordered else 0,
            "max": ordered[-1] if ordered else 0,
            "missing": missing[:100],
            "contiguous_from_one": ordered == list(range(1, len(ordered) + 1)),
        })
    tmdb = TMDB_RE.search(path.name)
    return {
        "series_rel": path.relative_to(ROOT.resolve()).as_posix(),
        "name": re.sub(r"\s*\{tmdb-\d+\}\s*$", "", path.name, flags=re.I),
        "tmdb_id": int(tmdb.group(1)) if tmdb else 0,
        "strm_count": strm_count,
        "seasons": seasons,
    }


def _scan_cloud_series(path: Path) -> dict:
    episodes: dict[int, set[int]] = {}
    video_count = 0
    # os.walk already returns file names from each directory listing.  Calling
    # Path.is_file() for every entry adds a separate remote stat request on a
    # CloudDrive2 mount and made a full-library scan take tens of minutes.
    for current, _, files in os.walk(path):
        for name in files:
            if Path(name).suffix.lower() not in VIDEO_SUFFIXES:
                continue
            match = EP_RE.search(name)
            if not match:
                continue
            season = int(match.group("season"))
            episode = int(match.group("episode"))
            episodes.setdefault(season, set()).add(episode)
            video_count += 1
    seasons = []
    for season, values in sorted(episodes.items()):
        ordered = sorted(values)
        missing = [n for n in range(ordered[0], ordered[-1] + 1) if n not in values] if ordered else []
        seasons.append({
            "season": season,
            "count": len(ordered),
            "min": ordered[0] if ordered else 0,
            "max": ordered[-1] if ordered else 0,
            "missing": missing[:100],
            "contiguous_from_one": ordered == list(range(1, len(ordered) + 1)),
        })
    tmdb = TMDB_RE.search(path.name)
    return {
        "series_rel": path.relative_to(CLOUD_ROOT.resolve()).as_posix(),
        "name": re.sub(r"\s*\{tmdb-\d+\}\s*$", "", path.name, flags=re.I),
        "tmdb_id": int(tmdb.group(1)) if tmdb else 0,
        "strm_count": video_count,
        "seasons": seasons,
        "source": "cloud",
    }


def _series_dirs(root: Path = CLOUD_ROOT) -> list[Path]:
    if not root.exists():
        return []
    found = []
    # Stop descending as soon as a TMDB-tagged series root is found.  The old
    # rglob walked every season and media file once just to discover series,
    # then _scan_cloud_series walked the same files again.  On a CloudDrive2
    # mount that doubled remote metadata calls and made a full scan look stuck.
    for current, directories, _ in os.walk(root):
        path = Path(current)
        if path != root and TMDB_RE.search(path.name):
            found.append(path)
            directories[:] = []
    return found


@router.post("/scan")
def scan(request: Request):
    # A synchronous FastAPI route runs in its worker thread pool.  CloudDrive2
    # directory traversal must not block the main asyncio event loop.
    _authorize(request)
    # Candidate discovery uses Symedia's local STRM index, which mirrors what
    # Emby currently sees and can be scanned in seconds.  Traversing every
    # video on the CloudDrive2 mount exceeded the reverse proxy timeout.  The
    # apply/preview path still re-reads and validates the real cloud files, so
    # no media is ever changed based on the local index alone.
    rows = [_scan_series(path) for path in _series_dirs(ROOT)]
    return {
        "root": str(ROOT), "source": "local-index-cloud-verified-on-apply",
        "series": [row for row in rows if row["strm_count"]],
    }


def _target_name(name: str, source_season: int, absolute_episode: int,
                 target_season: int, target_episode: int) -> str:
    pattern = re.compile(rf"(?i)S0*{source_season}E0*{absolute_episode}(?!\d)")
    updated, count = pattern.subn(f"S{target_season:02d}E{target_episode:02d}", name, count=1)
    if not count:
        raise HTTPException(status_code=409, detail=f"unable to rename {name}")
    updated = re.sub(rf"第\s*{absolute_episode}\s*集", f"第{target_episode}集", updated, count=1)
    return updated


def _build_exact_plan(series: Path, cloud_series: Path,
                      official_counts: list[int]) -> list[tuple[Path, Path]]:
    official_counts = [int(x) for x in official_counts if int(x) > 0]
    if len(official_counts) < 2:
        raise HTTPException(status_code=409, detail="official season list is incomplete")
    # CloudDrive2 is canonical.  The local STRM tree may already have been
    # cosmetically fixed by an older release and must not hide a bad cloud layout.
    scanned = _scan_cloud_series(cloud_series)
    if len(scanned["seasons"]) != 1:
        raise HTTPException(status_code=409, detail="exact repair requires one flattened source season")
    source = scanned["seasons"][0]
    total = sum(official_counts)
    if not source["contiguous_from_one"] or source["count"] != total:
        raise HTTPException(status_code=409, detail="episode total does not exactly match TMDB; manual review required")
    source_season = source["season"]
    mapping = {}
    absolute = 1
    for season, count in enumerate(official_counts, start=1):
        for episode in range(1, count + 1):
            mapping[absolute] = (season, episode)
            absolute += 1
    moves = []
    matched_video_count = 0
    for path in cloud_series.rglob("*"):
        if path.suffix.lower() not in CLOUD_MOVE_SUFFIXES or not path.is_file():
            continue
        match = EP_RE.search(path.name)
        if not match or int(match.group("season")) != source_season:
            continue
        old_episode = int(match.group("episode"))
        if old_episode not in mapping:
            continue
        if path.suffix.lower() in VIDEO_SUFFIXES:
            matched_video_count += 1
        target_season, target_episode = mapping[old_episode]
        target_dir = cloud_series / f"Season {target_season}"
        target = target_dir / _target_name(path.name, source_season, old_episode, target_season, target_episode)
        if target == path:
            continue
        moves.append((_inside_cloud(path), _inside_cloud(target)))
    if matched_video_count != total:
        raise HTTPException(
            status_code=409,
            detail=f"cloud video count is {matched_video_count}, expected {total}; refusing repair",
        )
    destinations = [dst for _, dst in moves]
    if len(destinations) != len(set(destinations)):
        raise HTTPException(status_code=409, detail="destination collision in repair plan")
    for source_path, target_path in moves:
        if target_path.exists() and target_path != source_path:
            raise HTTPException(status_code=409, detail=f"destination already exists: {target_path.name}")
    return moves


def _rebuild_local_series(series: Path, cloud_series: Path) -> None:
    """Recreate the Symedia-style local tree from canonical cloud files."""
    if series.exists():
        shutil.rmtree(series)
    series.mkdir(parents=True, exist_ok=True)
    for cloud_file in cloud_series.rglob("*"):
        if not cloud_file.is_file():
            continue
        relative = cloud_file.relative_to(cloud_series)
        destination = series / relative
        suffix = cloud_file.suffix.lower()
        if suffix in VIDEO_SUFFIXES:
            destination = destination.with_suffix(".strm")
            destination.parent.mkdir(parents=True, exist_ok=True)
            strm_target = CLOUD_STRM_PREFIX / cloud_series.relative_to(CLOUD_ROOT) / relative
            destination.write_text(str(strm_target), encoding="utf-8")
        elif suffix in (ALLOWED_SUFFIXES - {".strm"}):
            destination.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(cloud_file, destination)


def _restore_local_backup(series: Path, backup: Path) -> None:
    if series.exists():
        shutil.rmtree(series)
    with tarfile.open(backup, "r:gz") as archive:
        archive.extractall(series.parent, filter="data")


def _symedia_stop() -> bool:
    try:
        import docker
        container = docker.from_env().containers.get("symedia")
        was_running = container.status == "running"
        if was_running:
            container.stop(timeout=30)
        return was_running
    except Exception as exc:
        raise HTTPException(status_code=503, detail=f"unable to pause Symedia safely: {exc}")


def _symedia_start() -> None:
    try:
        import docker
        docker.from_env().containers.get("symedia").start()
    except Exception as exc:
        raise RuntimeError(f"unable to restart Symedia: {exc}")


def _refresh_emby() -> str:
    """Best-effort full library refresh using the notifier's configured Emby."""
    try:
        connection = sqlite3.connect(DB_PATH)
        connection.row_factory = sqlite3.Row
        row = connection.execute(
            "SELECT emby_url, emby_api_key FROM servers "
            "WHERE trim(emby_url)<>'' AND trim(emby_api_key)<>'' ORDER BY id LIMIT 1"
        ).fetchone()
        connection.close()
        if not row:
            return "Emby 未配置，需手动扫描媒体库"
        base = str(row["emby_url"]).rstrip("/")
        response = httpx.post(
            f"{base}/emby/Library/Refresh",
            headers={"X-Emby-Token": str(row["emby_api_key"])},
            timeout=30,
        )
        response.raise_for_status()
        return "已触发 Emby 媒体库扫描"
    except Exception as exc:
        return f"Emby 自动扫描失败，需手动扫描：{type(exc).__name__}: {exc}"


@router.post("/apply-exact")
async def apply_exact(request: Request):
    _authorize(request)
    body = await request.json()
    series = _series_path(body.get("series_rel", ""))
    cloud_series = _cloud_series_path(body.get("series_rel", ""))
    counts = body.get("official_counts") or []
    moves = _build_exact_plan(series, cloud_series, counts)
    if body.get("preview", True):
        return {
            "preview": True,
            "move_count": len(moves),
            "video_move_count": sum(1 for src, _ in moves if src.suffix.lower() in VIDEO_SUFFIXES),
            "metadata_move_count": sum(1 for src, _ in moves if src.suffix.lower() not in VIDEO_SUFFIXES),
            "examples": [{"from": a.name, "to": b.name} for a, b in moves[:12]],
        }
    STATE_DIR.mkdir(parents=True, exist_ok=True)
    action_id = f"{int(time.time())}-{secrets.token_hex(4)}"
    backup_dir = STATE_DIR / "backups"
    manifest_dir = STATE_DIR / "manifests"
    backup_dir.mkdir(exist_ok=True)
    manifest_dir.mkdir(exist_ok=True)
    backup = backup_dir / f"{action_id}.tar.gz"
    with tarfile.open(backup, "w:gz") as archive:
        archive.add(series, arcname=series.name)
    manifest = {
        "mode": "cloud-root-v2",
        "action_id": action_id,
        "series_rel": series.relative_to(ROOT.resolve()).as_posix(),
        "cloud_series_rel": cloud_series.relative_to(CLOUD_ROOT.resolve()).as_posix(),
        "backup": str(backup),
        "created_at": time.time(),
        "moves": [{"from": str(a), "to": str(b)} for a, b in moves],
    }
    manifest_path = manifest_dir / f"{action_id}.json"
    manifest_path.write_text(json.dumps(manifest, ensure_ascii=False, indent=2), encoding="utf-8")
    completed = []
    symedia_was_running = False
    try:
        _register_notification_suppression(series)
        symedia_was_running = _symedia_stop()
        for source_path, target_path in moves:
            target_path.parent.mkdir(parents=True, exist_ok=True)
            source_path.rename(target_path)
            if not target_path.exists():
                raise RuntimeError(f"CloudDrive2 move was not confirmed: {target_path.name}")
            completed.append((source_path, target_path))
        _rebuild_local_series(series, cloud_series)
    except Exception as exc:
        _remove_notification_suppression(series)
        try:
            _restore_local_backup(series, backup)
        except Exception:
            pass
        for source_path, target_path in reversed(completed):
            if target_path.exists() and not source_path.exists():
                source_path.parent.mkdir(parents=True, exist_ok=True)
                target_path.rename(source_path)
        raise HTTPException(status_code=500, detail=f"repair rolled back: {exc}")
    finally:
        if symedia_was_running:
            _symedia_start()
    refresh_message = _refresh_emby()
    return {
        "ok": True, "mode": "cloud-root-v2", "action_id": action_id, "move_count": len(moves),
        "video_move_count": sum(1 for src, _ in moves if src.suffix.lower() in VIDEO_SUFFIXES),
        "backup": str(backup), "refresh_message": refresh_message,
    }


@router.post("/undo/{action_id}")
async def undo(action_id: str, request: Request):
    _authorize(request)
    if not re.fullmatch(r"\d+-[0-9a-f]{8}", action_id):
        raise HTTPException(status_code=400, detail="invalid action id")
    manifest_path = STATE_DIR / "manifests" / f"{action_id}.json"
    if not manifest_path.exists():
        raise HTTPException(status_code=404, detail="repair action not found")
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    if manifest.get("mode") != "cloud-root-v2":
        raise HTTPException(status_code=409, detail="legacy metadata-only action cannot be undone by cloud repair")
    series = _series_path(manifest["series_rel"])
    backup = Path(manifest["backup"])
    moves = [(_inside_cloud(Path(item["from"])), _inside_cloud(Path(item["to"]))) for item in manifest["moves"]]
    for source_path, target_path in moves:
        if source_path.exists() or not target_path.exists():
            raise HTTPException(status_code=409, detail="library changed after repair; refusing automatic undo")
    symedia_was_running = _symedia_stop()
    try:
        _register_notification_suppression(series)
        for source_path, target_path in reversed(moves):
            source_path.parent.mkdir(parents=True, exist_ok=True)
            target_path.rename(source_path)
        _restore_local_backup(series, backup)
    finally:
        if symedia_was_running:
            _symedia_start()
    manifest_path.rename(manifest_path.with_suffix(".undone.json"))
    return {
        "ok": True, "action_id": action_id, "restored": len(moves),
        "refresh_message": _refresh_emby(),
    }
